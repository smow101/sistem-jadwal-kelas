/**
 * push_to_github.js
 * Pushes project files to GitHub via REST API (no git required).
 * Usage: node push_to_github.js <GITHUB_PAT>
 */

const https = require('https');
const fs = require('fs');
const path = require('path');

const OWNER = 'smow101';
const REPO = 'sistem-jadwal-kelas';
const BRANCH = 'main';
const COMMIT_MESSAGE = 'feat: Sistem Data Jadwal Kuliah - full SPA with redesigned UI';

// Files/dirs to skip entirely
const SKIP_NAMES = new Set([
  'node_modules', 'dist', '.env', '.git',
  'push_to_github.js', // skip this script itself
  'package-lock.json', // large, regenerated by npm install
]);

// Extensions to skip (binaries that are too large or irrelevant)
const SKIP_EXTENSIONS = new Set(['.png', '.jpg', '.jpeg', '.gif', '.ico', '.woff', '.woff2', '.ttf']);

const TOKEN = process.argv[2];
if (!TOKEN) {
  console.error('ERROR: Provide GitHub PAT as first argument.');
  console.error('Usage: node push_to_github.js ghp_xxxxxxxxxxxx');
  process.exit(1);
}

function apiRequest(method, urlPath, body) {
  return new Promise((resolve, reject) => {
    const data = body ? JSON.stringify(body) : null;
    const options = {
      hostname: 'api.github.com',
      path: urlPath,
      method,
      headers: {
        'Authorization': `Bearer ${TOKEN}`,
        'Accept': 'application/vnd.github+json',
        'X-GitHub-Api-Version': '2022-11-28',
        'User-Agent': 'push_to_github_script',
        'Content-Type': 'application/json',
      },
    };
    if (data) options.headers['Content-Length'] = Buffer.byteLength(data);

    const req = https.request(options, (res) => {
      let body = '';
      res.on('data', chunk => body += chunk);
      res.on('end', () => {
        try { resolve({ status: res.statusCode, body: JSON.parse(body) }); }
        catch { resolve({ status: res.statusCode, body }); }
      });
    });
    req.on('error', reject);
    if (data) req.write(data);
    req.end();
  });
}

async function getFileSha(filePath) {
  const r = await apiRequest('GET', `/repos/${OWNER}/${REPO}/contents/${filePath}?ref=${BRANCH}`);
  if (r.status === 200 && r.body && r.body.sha) return r.body.sha;
  return null;
}

async function uploadFile(localPath, repoPath) {
  const content = fs.readFileSync(localPath);
  const b64 = content.toString('base64');
  const sha = await getFileSha(repoPath);

  const payload = {
    message: `${COMMIT_MESSAGE}: ${repoPath}`,
    content: b64,
    branch: BRANCH,
  };
  if (sha) payload.sha = sha; // update existing file

  const r = await apiRequest('PUT', `/repos/${OWNER}/${REPO}/contents/${repoPath}`, payload);
  if (r.status === 200 || r.status === 201) {
    console.log(`  ✓  ${repoPath}`);
  } else {
    console.error(`  ✗  ${repoPath} → HTTP ${r.status}: ${JSON.stringify(r.body).slice(0, 120)}`);
  }
}

function collectFiles(dir, base = '') {
  const result = [];
  const entries = fs.readdirSync(dir, { withFileTypes: true });
  for (const entry of entries) {
    if (SKIP_NAMES.has(entry.name)) continue;
    if (entry.name.startsWith('.') && entry.name !== '.gitignore' && entry.name !== '.env.example') continue;

    const localPath = path.join(dir, entry.name);
    const repoPath = base ? `${base}/${entry.name}` : entry.name;

    if (entry.isDirectory()) {
      result.push(...collectFiles(localPath, repoPath));
    } else {
      const ext = path.extname(entry.name).toLowerCase();
      if (!SKIP_EXTENSIONS.has(ext)) {
        result.push({ localPath, repoPath });
      } else {
        console.log(`  ⚠  Skipping binary/image: ${repoPath}`);
      }
    }
  }
  return result;
}

async function ensureRepoAndBranch() {
  // Check repo exists
  const r = await apiRequest('GET', `/repos/${OWNER}/${REPO}`);
  if (r.status !== 200) {
    console.error(`ERROR: Cannot access repo ${OWNER}/${REPO}. Status: ${r.status}`);
    console.error('Make sure the repo exists and your PAT has repo scope.');
    process.exit(1);
  }
  console.log(`\n✓ Repo ${OWNER}/${REPO} found (default branch: ${r.body.default_branch})\n`);

  // Check if main branch exists; if not, we need to create it
  const br = await apiRequest('GET', `/repos/${OWNER}/${REPO}/git/ref/heads/${BRANCH}`);
  if (br.status === 404) {
    console.log(`Branch '${BRANCH}' not found. Will be created with first file upload.`);
    // We need a base commit — check if repo has ANY commits
    const commits = await apiRequest('GET', `/repos/${OWNER}/${REPO}/commits`);
    if (commits.status === 409 || (commits.status === 200 && commits.body.length === 0)) {
      console.log('Repo is empty — first file will initialize it.');
    }
  } else {
    console.log(`Branch '${BRANCH}' already exists.\n`);
  }
}

async function main() {
  const projectDir = path.resolve(__dirname);
  console.log(`\n=== GitHub Push Script ===`);
  console.log(`Repo   : ${OWNER}/${REPO}`);
  console.log(`Branch : ${BRANCH}`);
  console.log(`Source : ${projectDir}\n`);

  await ensureRepoAndBranch();

  const files = collectFiles(projectDir);
  console.log(`Found ${files.length} files to upload:\n`);

  for (const { localPath, repoPath } of files) {
    await uploadFile(localPath, repoPath);
  }

  console.log(`\n=== Done! ===`);
  console.log(`View your repo: https://github.com/${OWNER}/${REPO}`);
  console.log(`\nNext: Set up Vercel at https://vercel.com/new`);
  console.log(`Import from GitHub → ${OWNER}/${REPO}`);
  console.log(`Build Command   : npm run build`);
  console.log(`Output Directory: dist`);
  console.log(`Add env vars    : VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY`);
}

main().catch(err => {
  console.error('\nFATAL:', err.message);
  process.exit(1);
});
