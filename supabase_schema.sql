-- 1. PEMBUATAN TABEL schedules
CREATE TABLE IF NOT EXISTS public.schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matakuliah VARCHAR(100) NOT NULL,
    dosen VARCHAR(100) NOT NULL,
    kelas VARCHAR(20) NOT NULL,
    ruang VARCHAR(20) NOT NULL,
    hari VARCHAR(15) NOT NULL,
    jam_mulai TIME NOT NULL,
    jam_selesai TIME NOT NULL,
    created_at TIMESTAMPTZ DEFAULT NOW(),

    -- Database Check Constraints untuk integritas data
    CONSTRAINT check_jam_order CHECK (jam_selesai > jam_mulai),
    CONSTRAINT check_hari_valid CHECK (hari IN ('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu', 'Minggu')),
    CONSTRAINT check_matakuliah_not_empty CHECK (char_length(trim(matakuliah)) > 0),
    CONSTRAINT check_dosen_not_empty CHECK (char_length(trim(dosen)) > 0),
    CONSTRAINT check_kelas_not_empty CHECK (char_length(trim(kelas)) > 0),
    CONSTRAINT check_ruang_not_empty CHECK (char_length(trim(ruang)) > 0)
);

-- Komentar dokumentasi pada tabel dan kolom
COMMENT ON TABLE public.schedules IS 'Tabel utama pencatatan jadwal perkuliahan terstruktur sesuai SKPL Modul 2';
COMMENT ON COLUMN public.schedules.id IS 'Primary Key auto-increment';
COMMENT ON COLUMN public.schedules.matakuliah IS 'Nama mata kuliah perkuliahan';
COMMENT ON COLUMN public.schedules.dosen IS 'Nama dosen pengampu mata kuliah';
COMMENT ON COLUMN public.schedules.kelas IS 'Kode rombongan belajar / kelas';
COMMENT ON COLUMN public.schedules.ruang IS 'Kode ruangan kuliah';
COMMENT ON COLUMN public.schedules.hari IS 'Hari pelaksanaan kuliah (Senin s/d Minggu)';
COMMENT ON COLUMN public.schedules.jam_mulai IS 'Waktu mulai perkuliahan';
COMMENT ON COLUMN public.schedules.jam_selesai IS 'Waktu selesai perkuliahan';

-- 2. INDEX UNTUK DETEKSI BENTROK, PANEL OKUPANSI RUANG, DAN FILTER HARI/RUANG
-- Ekspresi lower(trim(ruang)) sama dengan perbandingan di trigger dan di aplikasi.
CREATE INDEX IF NOT EXISTS idx_schedules_hari_ruang_jam
ON public.schedules (hari, (lower(trim(ruang))), jam_mulai);

-- 3. TRIGGER PENCEGAHAN BENTROK JADWAL (LEVEL DATABASE)
-- Lapisan pertahanan kedua di belakang validasi aplikasi (mis. dua pengguna
-- menyimpan jadwal bersamaan). Aturan sama dengan aplikasi:
--   hari sama AND ruang sama (tanpa beda huruf besar/kecil & spasi tepi)
--   AND jam_mulai_lama < jam_selesai_baru AND jam_selesai_lama > jam_mulai_baru
-- Saat UPDATE, baris yang sedang diedit dikecualikan.
-- Pesan error WAJIB persis sama dengan TC-01.
CREATE OR REPLACE FUNCTION public.check_schedule_conflict()
RETURNS TRIGGER
LANGUAGE plpgsql
SET search_path = ''
AS $$
BEGIN
    -- Jam tidak valid / kosong dibiarkan lolos agar ditolak oleh CHECK constraint
    IF NEW.jam_mulai < NEW.jam_selesai THEN
        -- Kunci per (hari, ruang) selama transaksi agar dua simpan bersamaan
        -- tidak sama-sama lolos pengecekan.
        PERFORM pg_advisory_xact_lock(
            hashtext(coalesce(NEW.hari, '') || '|' || lower(trim(coalesce(NEW.ruang, ''))))
        );

        IF EXISTS (
            SELECT 1
            FROM public.schedules AS s
            WHERE s.hari = NEW.hari
              AND lower(trim(s.ruang)) = lower(trim(NEW.ruang))
              AND s.id IS DISTINCT FROM NEW.id
              AND s.jam_mulai < NEW.jam_selesai
              AND s.jam_selesai > NEW.jam_mulai
        ) THEN
            RAISE EXCEPTION 'Ruang sudah digunakan pada jam tersebut'
                USING ERRCODE = '23P01';
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

COMMENT ON FUNCTION public.check_schedule_conflict() IS 'Menolak INSERT/UPDATE jika hari dan ruang sama dengan rentang jam beririsan (TC-01)';

DROP TRIGGER IF EXISTS trg_check_schedule_conflict ON public.schedules;
CREATE TRIGGER trg_check_schedule_conflict
BEFORE INSERT OR UPDATE ON public.schedules
FOR EACH ROW
EXECUTE FUNCTION public.check_schedule_conflict();

-- 4. MENGAKTIFKAN ROW LEVEL SECURITY (RLS)
ALTER TABLE public.schedules ENABLE ROW LEVEL SECURITY;

-- 5. POLICIES CRUD UNTUK ROLE anon (Kebutuhan Workshop & Client App)
-- Hapus policy lama agar skrip idempotent
DROP POLICY IF EXISTS "Allow anon read schedules" ON public.schedules;
DROP POLICY IF EXISTS "Allow anon insert schedules" ON public.schedules;
DROP POLICY IF EXISTS "Allow anon update schedules" ON public.schedules;
DROP POLICY IF EXISTS "Allow anon delete schedules" ON public.schedules;

-- SELECT: izinkan pengguna publik membaca seluruh data jadwal
CREATE POLICY "Allow anon read schedules"
ON public.schedules
FOR SELECT
TO anon
USING (true);

-- INSERT: izinkan penambahan jadwal dengan validasi konsistensi
CREATE POLICY "Allow anon insert schedules"
ON public.schedules
FOR INSERT
TO anon
WITH CHECK (
    jam_selesai > jam_mulai
    AND char_length(trim(matakuliah)) > 0
    AND char_length(trim(dosen)) > 0
    AND char_length(trim(kelas)) > 0
    AND char_length(trim(ruang)) > 0
    AND hari IN ('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu', 'Minggu')
);

-- UPDATE: izinkan pembaruan jadwal dengan validasi konsistensi
CREATE POLICY "Allow anon update schedules"
ON public.schedules
FOR UPDATE
TO anon
USING (true)
WITH CHECK (
    jam_selesai > jam_mulai
    AND char_length(trim(matakuliah)) > 0
    AND char_length(trim(dosen)) > 0
    AND char_length(trim(kelas)) > 0
    AND char_length(trim(ruang)) > 0
    AND hari IN ('Senin', 'Selasa', 'Rabu', 'Kamis', 'Jumat', 'Sabtu', 'Minggu')
);

-- DELETE: izinkan penghapusan jadwal
CREATE POLICY "Allow anon delete schedules"
ON public.schedules
FOR DELETE
TO anon
USING (true);

